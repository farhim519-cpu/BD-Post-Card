def main():
    # Read existing quotes.ts
    with open('src/data/quotes.ts', 'r', encoding='utf-8') as f:
        content = f.read()

    # Find last quote ID
    pattern = r'\{\s*\"id\":\s*\"(q\d+)\"'
    ids = re.findall(pattern, content)
    last_num = 1050
    if ids:
        last_num = max(int(i[1:]) for i in ids)
    print(f"Current last quote ID: q{last_num:04d}")

    # Build new Quote items
    new_quotes = []
    current_num = last_num + 1

    for cat_name, cat_data in AUTHOR_QUOTES.items():
        author = cat_data['author_name']
        quotes_list = cat_data['quotes']
        print(f"Adding {len(quotes_list)} quotes for category: {cat_name} ({author})")
        for qtext in quotes_list:
            new_quotes.append({
                "id": f"q{current_num:04d}",
                "text": qtext,
                "category": cat_name,
                "author": author
            })
            current_num += 1

    print(f"Total new quotes to add: {len(new_quotes)}. New last ID: q{current_num-1:04d}")

    # Generate JSON string for new quotes
    # The file has: export const QUOTES: QuoteItem[] = [ ... ];
    # We will find the closing bracket '];'
    new_quotes_str = ""
    for item in new_quotes:
        new_quotes_str += f"""  {{
    "id": "{item['id']}",
    "text": {json.dumps(item['text'], ensure_ascii=False)},
    "category": {json.dumps(item['category'], ensure_ascii=False)},
    "author": {json.dumps(item['author'], ensure_ascii=False)}
  }},\n"""

    # Insert before the last '];'
    last_bracket_idx = content.rfind('];')
    if last_bracket_idx == -1:
        raise Exception("Could not find closing '];' in src/data/quotes.ts")

    updated_content = content[:last_bracket_idx] + new_quotes_str + content[last_bracket_idx:]

    with open('src/data/quotes.ts', 'w', encoding='utf-8') as f:
        f.write(updated_content)

    print(f"Successfully updated src/data/quotes.ts! Total quotes now: {len(ids) + len(new_quotes)}")

if __name__ == '__main__':
    main()
